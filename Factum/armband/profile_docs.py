"""The two files that make a profile folder self-explanatory.

This data may be used for the rest of Kyle's life. Formats have to stay
readable in ten years by someone who is not us and cannot run this app.
CSV and JSON handle the machine side of that; these two files handle
the human side:

    CLAUDE.md   for a Claude session pointed at the folder cold — the
                layout, the metrics, the person, the ground rules.
    README.md   the same thing for a human — a clinician, a future
                collaborator, Kyle himself, or us in five years.

Both are generated, and both are safe to edit: regeneration only
replaces a file that still carries the generator's marker line at the
top *and* was written by an older version. Delete the marker and the
file is yours forever.
"""

from __future__ import annotations

import datetime as dt
import os
from typing import Optional

# v3 — 2026-08-09. The subject context was wrong: it described a
# symmetric bilateral transradial amputation. Kyle's left limb is a long
# transradial (an inch above the wrist bone), his right is at the elbow
# with no forearm at all. Every generated doc that still claims two
# equivalent forearms must be rewritten, which is what this bump does.
DOCS_VERSION = 3
MARKER_PREFIX = "<!-- generated by Factum"
MARKER = (f"{MARKER_PREFIX} (docs v{DOCS_VERSION}) — edit freely; "
          f"delete this line and it will never be regenerated -->")


def _should_write(path: str) -> bool:
    """Write if absent, or if ours and stale. Never clobber human edits."""
    if not os.path.exists(path):
        return True
    try:
        with open(path, "r", encoding="utf-8") as f:
            first = f.readline().strip()
    except OSError:
        return False
    if not first.startswith(MARKER_PREFIX):
        return False          # someone removed the marker — hands off
    return first != MARKER    # ours, but from an older version


def _write(path: str, text: str) -> bool:
    if not _should_write(path):
        return False
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


