def readme_md(profile_name: str, profile_type: str = "subject",
              subject_context: str = "") -> str:
    context = subject_context.strip() or DEFAULT_SUBJECT_CONTEXT
    year = dt.datetime.now().year
    return f"""{MARKER}
# {profile_name} — recording archive

This folder is the complete record of one person's forearm nerve/muscle
recordings, made with a Mudra Band and an app called Factum.

**It is designed to outlive the app.** Everything here is plain text:
CSV for the signal data, JSON for metadata, Markdown for the writing.
You do not need Factum, or any particular program, to read any of it —
a text editor, Excel, or LibreOffice will open every file. If you have
found this folder in {year + 10} and have no idea what any of it is,
this file is where to start.

## Who this is

{context}

## What was recorded

Three electrodes sit around the forearm and sample about 1000 times per
second. In the data files the columns are always in this order:

| Column      | Meaning                                       |
|-------------|-----------------------------------------------|
| `timestamp` | milliseconds since the start of that recording |
| `ch1`       | ulnar electrode                               |
| `ch2`       | median electrode                              |
| `ch3`       | radial electrode                              |

Values run from -1 to +1 and are raw — nothing has been filtered,
smoothed or rescaled.

A **probe** is one short recording of one attempted movement, usually
30 seconds, named in his own words. A **session** is one visit: all the
probes recorded that day on that arm, kept together in one folder named
for the date and time.

## How to find your way around

- `profile.json` — who this profile is, and which session is open.
- `left/` and `right/` — one folder per arm. They are independent.
- `left/sessions/2026-08-14_1430/` — one visit. Inside it:
  - `REPORT.md` — **start here.** Plain-language summary of what was
    recorded that day, what looked good, what looked bad, what changed
    since the previous session, and what to try next.
  - `probes/` — the raw recordings, one CSV per probe. Every file
    begins with `#` comment lines describing itself.
  - `probes.json` — every probe's metadata and computed metrics in one
    place, if you would rather not open 20 CSVs.
  - `session_notes.md` — what was said and observed at the time.
  - `analysis.json` — every computed number, machine-readable.
- `left/placement_notes.md` — where the band was positioned, over time.
  This matters more than it sounds: the same movement recorded with the
  band 2 cm further up the arm produces a different signal.

## Reading a probe file

Open it in any text editor. The top of the file explains itself:

```
# profile: {profile_name}
# arm: left
# probe: curl ring finger
# started: 2026-08-14T14:33:07
# duration_s: 30
# sample_rate_hz: 1000
# effort: moderate
# fatigue: some
# his_confidence: 4
# filters: none
timestamp,ch1,ch2,ch3
0,0.02310,-0.01502,0.08911
1,0.01903,-0.02011,0.09104
```

`effort`, `fatigue` and `his_confidence` are his own ratings, recorded
at the time: how hard the movement was, how tired it left him, and how
sure he was that he did the same thing on each repetition. They are
subjective on purpose — they are often more predictive of whether a
movement will actually be usable day to day than the signal itself.

If a header says `status: incomplete`, the recording was interrupted
part-way. The data it contains is still valid.

## What the analysis was trying to find

Not the strongest signal — the **smallest set of movements he can
produce the same way every time, without tiring**. A weak movement
performed identically is more useful than a strong one that varies, and
a movement that exhausts him will not survive daily use however good it
looks on paper. The scoring in `REPORT.md` is weighted accordingly.

## A note on the numbers

Every metric is defined in plain language at the bottom of each
`REPORT.md`, and in `CLAUDE.md` next to this file. Nothing is computed
that is not explained somewhere in the folder.
"""


# =================================================================== writing


def write_profile_docs(profile_root: str, profile_name: str,
                       profile_type: str = "subject",
                       subject_context: str = "") -> list:
    """Write CLAUDE.md and README.md. Returns the paths actually written."""
    written = []
    pairs = (
        ("CLAUDE.md", claude_md(profile_name, profile_type, subject_context)),
        ("README.md", readme_md(profile_name, profile_type, subject_context)),
    )
    for name, text in pairs:
        path = os.path.join(profile_root, name)
        if _write(path, text):
            written.append(path)

    # placement/ gets a note explaining what belongs in it, since an
    # empty folder tells a future reader nothing.
    placement = os.path.join(profile_root, "placement")
    os.makedirs(placement, exist_ok=True)
    readme = os.path.join(placement, "README.md")
    if _write(readme, f"""{MARKER}
# Placement references

Photos, marks and measurements that let a helper put the band back in
the same place next time. Anything that answers "where exactly was it?"
belongs here: photos of the arm with the band on, close-ups of pen
marks, a ruler in shot, a diagram.

The same movement recorded with the band 2 cm further up the arm looks
like a different movement. Placement is the single biggest source of
day-to-day variation in this data, which is why it gets its own folder
and its own running log (`left/placement_notes.md`,
`right/placement_notes.md`).

Suggested naming: `2026-08-14_left_markA.jpg` — date first so the
folder sorts chronologically.
"""):
        written.append(readme)
    return written


